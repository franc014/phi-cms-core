<?php

use Illuminate\Filesystem\Filesystem;
use Illuminate\Support\Str;
use JFA\PhiCmsCore\Generators\BlockGenerator;

beforeEach(function (): void {
    $this->files = app(Filesystem::class);
    $this->sandbox = sys_get_temp_dir() . '/phi-cms-core-gen-' . Str::uuid();

    $this->files->ensureDirectoryExists($this->sandbox . '/app');
});

afterEach(function (): void {
    $this->files->deleteDirectory($this->sandbox);
});

it('generates admin block class and DTOs from schema config', function (): void {
    $config = [
        'example' => [
            'admin' => [
                'class' => 'App\\Generated\\Blocks\\Example',
                'label' => 'blocks.example.label',
                'icon' => 'heroicon-o-star',
            ],
            'dto' => 'App\\Generated\\Blocks\\Data\\ExampleData',
            'fields' => [
                'title' => [
                    'type' => 'string',
                    'required' => true,
                    'max' => 100,
                    'label' => 'blocks.example.title',
                ],
                'description' => [
                    'type' => 'text',
                    'required' => false,
                    'max' => 500,
                    'label' => 'blocks.example.description',
                ],
                'items' => [
                    'type' => 'repeater',
                    'label' => 'blocks.example.items.label',
                    'min' => 1,
                    'fields' => [
                        'name' => [
                            'type' => 'string',
                            'required' => true,
                            'max' => 50,
                            'label' => 'blocks.example.items.name',
                        ],
                    ],
                ],
            ],
        ],
    ];

    $result = app(BlockGenerator::class)->generate($config, $this->sandbox, 'App\\', false);

    $blockPath = $this->sandbox . '/app/Generated/Blocks/Example.php';
    $dtoPath = $this->sandbox . '/app/Generated/Blocks/Data/ExampleData.php';
    $itemPath = $this->sandbox . '/app/Generated/Blocks/Data/ExampleItemData.php';

    expect($this->files->exists($blockPath))->toBeTrue()
        ->and($this->files->exists($dtoPath))->toBeTrue()
        ->and($this->files->exists($itemPath))->toBeTrue()
        ->and($result['generated'])->toContain($blockPath, $dtoPath, $itemPath);

    expect($this->files->get($blockPath))
        ->toContain('namespace App\\Generated\\Blocks;')
        ->toContain('class Example implements ContentBlock')
        ->toContain('Generated by phi-cms:generate-blocks');

    expect($this->files->get($dtoPath))
        ->toContain('final readonly class ExampleData implements BlockData')
        ->toContain('public string $title,')
        ->toContain('public ?string $description,');

    expect($this->files->get($itemPath))
        ->toContain('final readonly class ExampleItemData')
        ->toContain('public string $name,');
});

it('skips files that already exist', function (): void {
    $blockPath = $this->sandbox . '/app/Generated/Blocks/Example.php';
    $this->files->ensureDirectoryExists(dirname($blockPath));
    $this->files->put($blockPath, '<?php // existing');

    $config = [
        'example' => [
            'admin' => [
                'class' => 'App\\Generated\\Blocks\\Example',
                'icon' => 'heroicon-o-star',
            ],
            'dto' => 'App\\Generated\\Blocks\\Data\\ExampleData',
            'fields' => [],
        ],
    ];

    $result = app(BlockGenerator::class)->generate($config, $this->sandbox, 'App\\', false);

    expect($this->files->get($blockPath))->toBe('<?php // existing')
        ->and($result['skipped'])->toContain($blockPath)
        ->and($result['generated'])->not->toContain($blockPath);
});

it('overwrites generated files with force', function (): void {
    $blockPath = $this->sandbox . '/app/Generated/Blocks/Example.php';
    $this->files->ensureDirectoryExists(dirname($blockPath));
    $this->files->put($blockPath, "<?php\n\n// Generated by phi-cms:generate-blocks\n// old version");

    $config = [
        'example' => [
            'admin' => [
                'class' => 'App\\Generated\\Blocks\\Example',
                'icon' => 'heroicon-o-star',
            ],
            'dto' => 'App\\Generated\\Blocks\\Data\\ExampleData',
            'fields' => [],
        ],
    ];

    $result = app(BlockGenerator::class)->generate($config, $this->sandbox, 'App\\', true);

    expect($this->files->get($blockPath))->toContain('class Example implements ContentBlock')
        ->and($result['generated'])->toContain($blockPath)
        ->and($result['skipped'])->not->toContain($blockPath);
});

it('protects handwritten files even with force', function (): void {
    $blockPath = $this->sandbox . '/app/Generated/Blocks/Example.php';
    $this->files->ensureDirectoryExists(dirname($blockPath));
    $this->files->put($blockPath, "<?php\n\nnamespace App\\Generated\\Blocks;\n\nclass Example {}");

    $config = [
        'example' => [
            'admin' => [
                'class' => 'App\\Generated\\Blocks\\Example',
                'icon' => 'heroicon-o-star',
            ],
            'dto' => 'App\\Generated\\Blocks\\Data\\ExampleData',
            'fields' => [],
        ],
    ];

    $result = app(BlockGenerator::class)->generate($config, $this->sandbox, 'App\\', true);

    expect($this->files->get($blockPath))->toContain('class Example {}')
        ->and($result['protected'])->toContain($blockPath);
});

it('overwrites handwritten files with force and all', function (): void {
    $blockPath = $this->sandbox . '/app/Generated/Blocks/Example.php';
    $this->files->ensureDirectoryExists(dirname($blockPath));
    $this->files->put($blockPath, "<?php\n\nnamespace App\\Generated\\Blocks;\n\nclass Example {}");

    $config = [
        'example' => [
            'admin' => [
                'class' => 'App\\Generated\\Blocks\\Example',
                'icon' => 'heroicon-o-star',
            ],
            'dto' => 'App\\Generated\\Blocks\\Data\\ExampleData',
            'fields' => [],
        ],
