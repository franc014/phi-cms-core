it('does not write files in dry-run mode', function (): void {
    $config = [
        'example' => [
            'admin' => [
                'class' => 'App\\Generated\\Blocks\\Example',
                'icon' => 'heroicon-o-star',
            ],
            'dto' => 'App\\Generated\\Blocks\\Data\\ExampleData',
            'fields' => [
                'title' => [
                    'type' => 'string',
                    'required' => true,
                    'max' => 100,
                ],
            ],
        ],
    ];

    $result = app(BlockGenerator::class)->generate($config, $this->sandbox, 'App\\', false, false, true);

    $blockPath = $this->sandbox . '/app/Generated/Blocks/Example.php';
    $dtoPath = $this->sandbox . '/app/Generated/Blocks/Data/ExampleData.php';

    expect($this->files->exists($blockPath))->toBeFalse()
        ->and($this->files->exists($dtoPath))->toBeFalse()
        ->and($result['generated'])->toContain($blockPath, $dtoPath);
});

