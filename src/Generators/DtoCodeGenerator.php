<?php

namespace JFA\PhiCmsCore\Generators;

use Illuminate\Support\Str;
use JFA\PhiCmsCore\Schema\Fields\RepeaterField;
use JFA\PhiCmsCore\Schema\Schema;

final class DtoCodeGenerator
{
    private const GENERATED_MARKER = 'Generated by phi-cms:generate-blocks';

    public function __construct(private FieldCodeRenderer $fieldRenderer) {}

    /**
     * @return array<string, string>
     */
    public function generateAll(Schema $schema): array
    {
        $classes = [
            (string) $schema->dtoClass => $this->generateTopLevelDto($schema),
        ];

        foreach ($schema->fields as $field) {
            if ($field instanceof RepeaterField) {
                $itemClass = $this->dtoNamespace((string) $schema->dtoClass) . '\\' . $this->fieldRenderer->repeaterItemClassName($schema->type, $field->name);

                $classes[$itemClass] = $this->generateRepeaterItem($schema, $field);
            }
        }

        return $classes;
    }

    public function generateTopLevelDto(Schema $schema): string
    {
        $class = class_basename((string) $schema->dtoClass);
        $namespace = $this->dtoNamespace((string) $schema->dtoClass);
        $marker = self::GENERATED_MARKER;

        $constructor = [];
        $docblock = [];
        $validation = [];
        $arrayLines = [];
        $viewLines = [];

        foreach ($schema->fields as $field) {
            if ($field instanceof RepeaterField) {
                $constructor[] = '        public array $' . $field->name . ',';
                $docblock[] = ' * @param  array<int, ' . $this->fieldRenderer->repeaterItemClassName($schema->type, $field->name) . '>  $' . $field->name;
                $validation[] = $this->fieldRenderer->renderRepeaterValidation($schema, $field);
                $arrayLines[] = "            '{$field->name}' => array_map(\n                fn (" . $this->fieldRenderer->repeaterItemClassName($schema->type, $field->name) . " \$item): array => \$item->toArray(),\n                \$this->{$field->name},\n            ),";
                $viewLines[] = "            '{$field->name}' => \$this->{$field->name},";

                continue;
            }

            $code = $this->fieldRenderer->renderField($schema, $field);
            $constructor[] = '        public ' . $code->type . ' $' . $code->property . ',';
            $validation[] = $code->validation;
            $arrayLines[] = $code->arrayLine;
            $viewLines[] = $code->viewLine;
        }

        $docblock = array_values(array_filter($docblock));
        $propertyBlock = implode("\n", $constructor);
        $validationBlock = implode("\n\n", array_filter($validation));
        $arrayBlock = implode("\n", $arrayLines);
        $viewBlock = implode("\n", $viewLines);
        $docblockBlock = $docblock === [] ? '' : implode("\n", $docblock) . "\n";
        $assignmentsBlock = $this->renderAssignments($schema);

        $template = <<<'PHP'
<?php

// %s

namespace %s;

use InvalidArgumentException;
use JFA\PhiCmsPresenter\Contracts\BlockData;

final readonly class %s implements BlockData
{
    /**
%s     */
    public function __construct(
%s
    ) {}

    /**
     * @param  array<string, mixed>  $data
     */
    public static function fromArray(array $data): static
    {
%s

        return new self(
%s
        );
    }

    /**
     * @return array<string, mixed>
     */
    public function toArray(): array
    {
        return [
%s
        ];
    }

    /**
     * @return array<string, mixed>
     */
    public function toViewData(): array
    {
        return [
%s
        ];
    }
}

PHP;

        return sprintf(
            $template,
            $marker,
            $namespace,
            $class,
            $docblockBlock,
            $propertyBlock,
            $validationBlock,
            $assignmentsBlock,
            $arrayBlock,
            $viewBlock,
        );
    }

    public function generateRepeaterItem(Schema $schema, RepeaterField $field): string
    {
        $class = $this->fieldRenderer->repeaterItemClassName($schema->type, $field->name);
        $namespace = $this->dtoNamespace((string) $schema->dtoClass);
        $marker = self::GENERATED_MARKER;

        $constructor = [];
        $validation = [];
        $arrayLines = [];
        $assignments = [];

        foreach ($field->fields as $childField) {
            $code = $this->fieldRenderer->renderRepeaterChildField($schema, $field, $childField);
            $constructor[] = '        public ' . $code->type . ' $' . $code->property . ',';
            $validation[] = $code->validation;
            $arrayLines[] = $code->arrayLine;
            $assignments[] = '            ' . $code->property . ': ' . $code->assignment . ',';
        }

        $constructorBlock = implode("\n", $constructor);
        $validationBlock = implode("\n\n", $validation);
        $arrayBlock = implode("\n", $arrayLines);
        $assignmentsBlock = implode("\n", $assignments);

        $template = <<<'PHP'
<?php

// %s

namespace %s;

use InvalidArgumentException;

final readonly class %s
{
    public function __construct(
%s
    ) {}

    /**
     * @param  array<string, mixed>  $data
     */
    public static function fromArray(array $data): self
    {
%s

        return new self(
%s
        );
    }

    /**
     * @return array<string, mixed>
     */
    public function toArray(): array
    {
        return [
%s
        ];
    }
}

PHP;

        return sprintf(
            $template,
            $marker,
            $namespace,
            $class,
            $constructorBlock,
            $validationBlock,
            $assignmentsBlock,
            $arrayBlock,
        );
    }

    private function renderAssignments(Schema $schema): string
    {
        $lines = [];

        foreach ($schema->fields as $field) {
            if ($field instanceof RepeaterField) {
                $lines[] = '            ' . $field->name . ': $' . $field->name . ',';

                continue;
            }

            $code = $this->fieldRenderer->renderField($schema, $field);
            $lines[] = '            ' . $code->property . ': ' . $code->assignment . ',';
        }

        return implode("\n", $lines);
    }

    private function dtoNamespace(string $class): string
    {
        return trim((string) Str::beforeLast($class, '\\'), '\\');
    }
}
