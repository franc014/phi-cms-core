<?php

namespace JFA\PhiCmsCore\Generators;

use Illuminate\Filesystem\Filesystem;
use Illuminate\Support\Str;
use JFA\PhiCmsCore\Schema\FieldFactory;
use JFA\PhiCmsCore\Schema\SchemaRegistry;

final class BlockGenerator
{
    private const GENERATED_MARKER = 'Generated by phi-cms:generate-blocks';

    public function __construct(
        private Filesystem $files,
        private AdminBlockCodeGenerator $adminGenerator,
        private DtoCodeGenerator $dtoGenerator,
    ) {}

    /**
     * @param  array<string, array<string, mixed>>  $config
     * @return array{generated: array<int, string>, skipped: array<int, string>, protected: array<int, string>}
     */
    public function generate(array $config, string $basePath, string $rootNamespace, bool $force = false, bool $all = false, bool $dryRun = false): array
    {
        $registry = SchemaRegistry::fromConfig($config, new FieldFactory);

        $result = [
            'generated' => [],
            'skipped' => [],
            'protected' => [],
        ];

        foreach ($registry->all() as $schema) {
            $result = $this->mergeResult($result, $this->generateSchema($schema, $basePath, $rootNamespace, $force, $all, $dryRun));
        }

        return $result;
    }

    /**
     * @return array{generated: array<int, string>, skipped: array<int, string>, protected: array<int, string>}
     */
    private function generateSchema($schema, string $basePath, string $rootNamespace, bool $force, bool $all, bool $dryRun): array
    {
        $result = [
            'generated' => [],
            'skipped' => [],
            'protected' => [],
        ];

        if ($schema->adminClass !== null && $this->shouldGenerate($schema->adminClass, $rootNamespace)) {
            $result = $this->mergeResult(
                $result,
                $this->writeGeneratedClass(
                    $this->classPath($schema->adminClass, $basePath, $rootNamespace),
                    $this->adminGenerator->generate($schema),
                    $force,
                    $all,
                    $dryRun,
                ),
            );
        }

        if ($schema->dtoClass !== null && $this->shouldGenerate($schema->dtoClass, $rootNamespace)) {
            foreach ($this->dtoGenerator->generateAll($schema) as $class => $code) {
                $result = $this->mergeResult(
                    $result,
                    $this->writeGeneratedClass(
                        $this->classPath($class, $basePath, $rootNamespace),
                        $code,
                        $force,
                        $all,
                        $dryRun,
                    ),
                );
            }
        }

        return $result;
    }

    private function shouldGenerate(string $class, string $rootNamespace): bool
    {
        return Str::startsWith($class, $rootNamespace);
    }

    private function classPath(string $class, string $basePath, string $rootNamespace): string
    {
        $relativeClass = Str::after($class, $rootNamespace);

        return $basePath . '/app/' . str_replace('\\', '/', $relativeClass) . '.php';
    }

    /**
     * @return array{generated: array<int, string>, skipped: array<int, string>, protected: array<int, string>}
     */
    private function writeGeneratedClass(string $path, string $code, bool $force, bool $all, bool $dryRun): array
    {
        if (! $this->files->exists($path)) {
            if (! $dryRun) {
                $this->files->ensureDirectoryExists(dirname($path));
                $this->files->put($path, $code);
            }

            return [
                'generated' => [$path],
                'skipped' => [],
                'protected' => [],
            ];
        }

        if (! $force) {
            return [
                'generated' => [],
                'skipped' => [$path],
                'protected' => [],
            ];
        }

        if (! $all && ! $this->isGeneratedFile($path)) {
            return [
                'generated' => [],
                'skipped' => [],
                'protected' => [$path],
            ];
        }

        if (! $dryRun) {
            $this->files->put($path, $code);
        }

        return [
            'generated' => [$path],
            'skipped' => [],
            'protected' => [],
        ];
    }

    private function isGeneratedFile(string $path): bool
    {
        return Str::contains($this->files->get($path), self::GENERATED_MARKER);
    }

    /**
     * @param  array{generated: array<int, string>, skipped: array<int, string>, protected: array<int, string>}  $left
     * @param  array{generated: array<int, string>, skipped: array<int, string>, protected: array<int, string>}  $right
     * @return array{generated: array<int, string>, skipped: array<int, string>, protected: array<int, string>}
     */
    private function mergeResult(array $left, array $right): array
    {
        return [
            'generated' => array_values(array_merge($left['generated'], $right['generated'])),
            'skipped' => array_values(array_merge($left['skipped'], $right['skipped'])),
            'protected' => array_values(array_merge($left['protected'], $right['protected'])),
        ];
    }
}
