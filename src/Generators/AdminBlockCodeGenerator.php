<?php

namespace JFA\PhiCmsCore\Generators;

use Illuminate\Support\Str;
use JFA\PhiCmsCore\Schema\Schema;

final class AdminBlockCodeGenerator
{
    private const GENERATED_MARKER = 'Generated by phi-cms:generate-blocks';

    public function generate(Schema $schema): string
    {
        $class = class_basename((string) $schema->adminClass);
        $type = $schema->type;
        $label = $schema->adminMeta['label'] ?? Str::headline($schema->type);
        $icon = $schema->adminMeta['icon'] ?? 'heroicon-o-bars-3';
        $namespace = $this->classNamespace((string) $schema->adminClass);
        $marker = self::GENERATED_MARKER;
        $typeLiteral = var_export($type, true);
        $labelLiteral = var_export($label, true);
        $iconLiteral = var_export($icon, true);

        $template = <<<'PHP'
<?php

// %s

namespace %s;

use Filament\Forms\Components\Builder\Block;
use JFA\PhiCmsCore\Contracts\ContentBlock;
use JFA\PhiCmsCore\Forms\Blocks\BlockSettings;
use JFA\PhiCmsCore\Forms\Blocks\Concerns\RendersSchemaFields;
use JFA\PhiCmsCore\Schema\SchemaRegistry;

class %s implements ContentBlock
{
    use BlockSettings;
    use RendersSchemaFields;

    public static function make(): Block
    {
        $schema = app(SchemaRegistry::class)->get(%s);
        $components = self::schemaComponents(%s);

        return Block::make($schema->type)
            ->schema(array_values($components))
            ->label(function (?array $state) use ($schema): string {
                return self::setBlockLabel(
                    $state,
                    __($schema->adminMeta['label'] ?? %s),
                    $schema->adminMeta['label_field'] ?? null,
                );
            })
            ->icon($schema->adminMeta['icon'] ?? %s);
    }
}

PHP;

        return sprintf(
            $template,
            $marker,
            $namespace,
            $class,
            $typeLiteral,
            $typeLiteral,
            $labelLiteral,
            $iconLiteral,
        );
    }

    private function classNamespace(string $class): string
    {
        return trim((string) Str::beforeLast($class, '\\'), '\\');
    }
}
